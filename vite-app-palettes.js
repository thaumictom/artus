import { mkdirSync, readFileSync, watch, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DittoTones } from 'dittotones';
import { tailwindRamps } from 'dittotones/ramps/tailwind';
import { formatCss } from 'culori';

const source = new URL('./src-tauri/src/theme_colors.toml', import.meta.url);
const paletteDir = new URL('./src/css/themes/palettes/', import.meta.url);
const paletteIndex = new URL('./src/css/themes/palettes.css', import.meta.url);
const darkShades = new Set(['600', '700', '800', '900', '950']);
const ditto = new DittoTones({ ramps: tailwindRamps });

/** @param {URL} file @param {string} contents */
function writeIfChanged(file, contents) {
	try {
		if (readFileSync(file, 'utf8') === contents) return;
	} catch (error) {
		if (/** @type {NodeJS.ErrnoException} */ (error).code !== 'ENOENT') throw error;
	}
	writeFileSync(file, contents);
}

function generatePalettes() {
	/** @type {{ primary: Record<string, number[]>, highlight: Record<string, number[]> }} */
	const sections = { primary: {}, highlight: {} };
	/** @type {'primary' | 'highlight' | undefined} */
	let section;
	for (const line of readFileSync(source, 'utf8').split(/\r?\n/)) {
		const heading = line.match(/^\[(primary|highlight)\]$/);
		if (heading) section = /** @type {'primary' | 'highlight'} */ (heading[1]);
		const entry = line.match(/^(\w+)\s*=\s*\[([^\]]+)\]$/);
		if (entry && section) sections[section][entry[1]] = entry[2].split(',').map(Number);
	}

	// Lunar Renewal has no OCR entry; retain its approximate UI colors.
	sections.primary.LUNAR_RENEWAL = [160, 39, 48];
	sections.highlight.LUNAR_RENEWAL = [240, 194, 105];

	mkdirSync(paletteDir, { recursive: true });
	const imports = ['/* Generated by the Artus Vite palette plugin from theme_colors.toml. */'];
	for (const [name, primary] of Object.entries(sections.primary)) {
		const highlight = sections.highlight[name];
		if (!highlight) throw new Error(`Missing highlight color for ${name}`);
		const slug = name.toLowerCase().replaceAll('_', '-');
		const lines = [`/* ${name}: dittotones Tailwind v4 ramps. */`, '@theme static {'];
		for (const role of ['primary', 'highlight']) {
			const rgb = role === 'primary' ? primary : highlight;
			const hex = `#${rgb.map((channel) => channel.toString(16).padStart(2, '0')).join('')}`;
			const { scale } = ditto.generate(hex);
			for (const [shade, color] of Object.entries(scale)) {
				const rounded = {
					...color,
					l: Number(color.l.toFixed(4)),
					c: Number(color.c.toFixed(4)),
					h: color.h === undefined ? undefined : Number(color.h.toFixed(2)),
				};
				const base = formatCss(rounded);
				const value = darkShades.has(shade)
					? `color-mix(in oklch, ${base}, black var(--theme-darken-${shade}))`
					: base;
				lines.push(`\t--color-wf-${slug}-${role}-${shade}: ${value};`);
			}
		}
		lines.push('}', '');
		writeIfChanged(new URL(`${slug}.css`, paletteDir), lines.join('\n'));
		imports.push(`@import './palettes/${slug}.css';`);
	}
	writeIfChanged(paletteIndex, `${imports.join('\n')}\n`);
}

/** @returns {import('vite').Plugin} */
export function appPalettesPlugin() {
	return {
		name: 'artus-app-palettes',
		enforce: 'pre',
		configResolved() {
			generatePalettes();
		},
		configureServer(server) {
			const watcher = watch(fileURLToPath(source), () => {
				generatePalettes();
				server.ws.send({ type: 'full-reload' });
			});
			server.httpServer?.once('close', () => watcher.close());
		},
	};
}
